// Vec<T> Implementation
// ============================================================================

// NOTE: encode_cdr2_le keeps the legacy sub-buffer body — it does NOT
// fall back to the new (1.6.1f) default impl that delegates to
// encode_cdr2_le_at. Reason: encode_cdr2_le_at aligns inner elements
// per the XCDR2 spec, while the symmetric Cdr2Decode for Vec<T> reads
// elements without alignment via sub-buffer slicing (no decode_cdr2_le_at
// exists yet on the trait). Switching the encoder to delegate would emit
// aligned bytes that the legacy decoder cannot read back symmetrically.
// The two paths are intentionally separate wire formats: _le for legacy
// roundtrip contracts, _at for spec-aligned offset propagation in composite
// outer encoders. Migration of the decoder to a symmetric aligned path
// (decode_cdr2_le_at) is tracked as sous-chantier 1.6.11 in
// ADR-CHANTIER-1.6 §10.15.
impl<T: Cdr2Encode> Cdr2Encode for Vec<T> {
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        let mut offset = 0;

        // Write sequence length (u32)
        let len = self.len() as u32;
        if dst.len() < 4 {
            return Err(CdrError::BufferTooSmall);
        }
        dst[offset..offset + 4].copy_from_slice(&len.to_le_bytes());
        offset += 4;

        // Write each element
        for elem in self {
            let used = elem.encode_cdr2_le(&mut dst[offset..])?;
            offset += used;
        }

        Ok(offset)
    }

    fn max_cdr2_size(&self) -> usize {
        // Conservative estimate: 4 bytes for length + sum of element sizes
        4 + self.iter().map(|e| e.max_cdr2_size()).sum::<usize>()
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        let len = u32::try_from(self.len()).map_err(|_| CdrError::DataTooLarge)?;
        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 > dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        dst[*offset..*offset + pad].fill(0);
        *offset += pad;
        dst[*offset..*offset + 4].copy_from_slice(&len.to_le_bytes());
        *offset += 4;
        for elem in self {
            elem.encode_cdr2_le_at(dst, offset)?;
        }
        Ok(())
    }
}

impl<T: Cdr2Decode> Cdr2Decode for Vec<T> {
    fn decode_cdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        let mut offset = 0;

        // Read sequence length
        if src.len() < 4 {
            return Err(CdrError::UnexpectedEof);
        }
        let len = u32::from_le_bytes([src[0], src[1], src[2], src[3]]) as usize;
        offset += 4;

        // Guard against bogus lengths: each element is at least 1 byte
        if len > src.len().saturating_sub(offset) {
            return Err(CdrError::UnexpectedEof);
        }

        // Read elements
        let mut vec = Vec::with_capacity(len);
        for _ in 0..len {
            let (elem, used) = T::decode_cdr2_le(&src[offset..])?;
            vec.push(elem);
            offset += used;
        }

        Ok((vec, offset))
    }

    /// Spec-aligned decoder symmetric with `encode_cdr2_le_at`:
    /// - Pads to 4 before the u32 length prefix (XCDR2 §7.4.3.4.1 Tab.15).
    /// - Pad bytes are SKIPPED without validating their value
    ///   (§7.4.3.2 Table 37: "value of padded bytes left unspecified").
    /// - Delegates each element to `T::decode_cdr2_le_at` so the global
    ///   cursor propagates through nested types.
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 > src.len() {
            return Err(CdrError::UnexpectedEof);
        }
        *offset += pad;
        let mut len_bytes = [0u8; 4];
        len_bytes.copy_from_slice(&src[*offset..*offset + 4]);
        let len = u32::from_le_bytes(len_bytes) as usize;
        *offset += 4;

        // Guard against bogus lengths: each element is at least 1 byte.
        if len > src.len().saturating_sub(*offset) {
            return Err(CdrError::UnexpectedEof);
        }

        let mut vec = Vec::with_capacity(len);
        for _ in 0..len {
            vec.push(T::decode_cdr2_le_at(src, offset)?);
        }
        Ok(vec)
    }
}

// ============================================================================
// HashMap<K, V> Implementation
// ============================================================================

// NOTE: encode_cdr2_le keeps the legacy sub-buffer body. See the same
// note on `impl Cdr2Encode for Vec<T>` for the rationale (legacy decoder
// does not align; encoder must stay symmetric).
impl<K: Cdr2Encode, V: Cdr2Encode> Cdr2Encode for std::collections::HashMap<K, V> {
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        let mut offset = 0;

        // Write map length (u32)
        let len = self.len() as u32;
        if dst.len() < 4 {
            return Err(CdrError::BufferTooSmall);
        }
        dst[offset..offset + 4].copy_from_slice(&len.to_le_bytes());
        offset += 4;

        // Write each key-value pair
        for (key, value) in self {
            let used = key.encode_cdr2_le(&mut dst[offset..])?;
            offset += used;
            let used = value.encode_cdr2_le(&mut dst[offset..])?;
            offset += used;
        }

        Ok(offset)
    }

    fn max_cdr2_size(&self) -> usize {
        // Conservative estimate
        4 + self.len() * 64 // rough estimate per entry
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        let len = u32::try_from(self.len()).map_err(|_| CdrError::DataTooLarge)?;
        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 > dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        dst[*offset..*offset + pad].fill(0);
        *offset += pad;
        dst[*offset..*offset + 4].copy_from_slice(&len.to_le_bytes());
        *offset += 4;
        for (key, value) in self {
            key.encode_cdr2_le_at(dst, offset)?;
            value.encode_cdr2_le_at(dst, offset)?;
        }
        Ok(())
    }
}

impl<K, V> Cdr2Decode for std::collections::HashMap<K, V>
where
    K: Cdr2Decode + std::cmp::Eq + std::hash::Hash,
    V: Cdr2Decode,
{
    fn decode_cdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        let mut offset = 0;

        // Read map length
        if src.len() < 4 {
            return Err(CdrError::UnexpectedEof);
        }
        let len = u32::from_le_bytes([src[0], src[1], src[2], src[3]]) as usize;
        offset += 4;

        // Guard against bogus lengths: each KV pair is at least 2 bytes
        if len > src.len().saturating_sub(offset) / 2 {
            return Err(CdrError::UnexpectedEof);
        }

        // Read key-value pairs
        let mut map = std::collections::HashMap::with_capacity(len);
        for _ in 0..len {
            let (key, used) = K::decode_cdr2_le(&src[offset..])?;
            offset += used;
            let (value, used) = V::decode_cdr2_le(&src[offset..])?;
            offset += used;
            map.insert(key, value);
        }

        Ok((map, offset))
    }

    /// Spec-aligned decoder symmetric with `encode_cdr2_le_at`. See the
    /// `Vec<T>::decode_cdr2_le_at` docstring for the alignment + pad-skip
    /// contract.
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 > src.len() {
            return Err(CdrError::UnexpectedEof);
        }
        *offset += pad;
        let mut len_bytes = [0u8; 4];
        len_bytes.copy_from_slice(&src[*offset..*offset + 4]);
        let len = u32::from_le_bytes(len_bytes) as usize;
        *offset += 4;

        // Guard against bogus lengths: each KV pair is at least 2 bytes.
        if len > src.len().saturating_sub(*offset) / 2 {
            return Err(CdrError::UnexpectedEof);
        }

        let mut map = std::collections::HashMap::with_capacity(len);
        for _ in 0..len {
            let key = K::decode_cdr2_le_at(src, offset)?;
            let value = V::decode_cdr2_le_at(src, offset)?;
            map.insert(key, value);
        }
        Ok(map)
    }
}

/// CDR2 encoding for &str (borrows to String encoding)
impl Cdr2Encode for &str {
    fn max_cdr2_size(&self) -> usize {
        4 + self.len() + 1
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        let bytes = self.as_bytes();
        let str_len = bytes.len();
        let cdr_len: u32 = (str_len + 1)
            .try_into()
            .map_err(|_| CdrError::DataTooLarge)?;

        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 + str_len + 1 > dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        dst[*offset..*offset + pad].fill(0);
        *offset += pad;
        dst[*offset..*offset + 4].copy_from_slice(&cdr_len.to_le_bytes());
        *offset += 4;
        dst[*offset..*offset + str_len].copy_from_slice(bytes);
        *offset += str_len;
        dst[*offset] = 0;
        *offset += 1;
        Ok(())
    }
}

// ============================================================================
// bool Implementation (XTypes 1.3 Section 7.4.1.3)
// CDR2 boolean: 1 byte, 0x00 = false, 0x01 = true
// ============================================================================

impl Cdr2Encode for bool {
    fn max_cdr2_size(&self) -> usize {
        1
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        if *offset >= dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        dst[*offset] = u8::from(*self);
        *offset += 1;
        Ok(())
    }
}

impl Cdr2Decode for bool {
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        if *offset >= src.len() {
            return Err(CdrError::UnexpectedEof);
        }
        let byte = src[*offset];
        *offset += 1;
        match byte {
            0 => Ok(false),
            1 => Ok(true),
            v => Err(CdrError::Other(format!("invalid boolean value: {v}"))),
        }
    }
}

// ============================================================================
// char Implementation (XTypes 1.3 Section 7.4.1.4 -- char8 only)
// CDR2 char8: 1 byte, ASCII range
// ============================================================================

impl Cdr2Encode for char {
    fn max_cdr2_size(&self) -> usize {
        1
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        if *offset >= dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        if !self.is_ascii() {
            return Err(CdrError::InvalidEncoding);
        }
        dst[*offset] = *self as u8;
        *offset += 1;
        Ok(())
    }
}

impl Cdr2Decode for char {
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        if *offset >= src.len() {
            return Err(CdrError::UnexpectedEof);
        }
        // char8: any byte value maps to a char (ASCII subset per spec,
        // but we accept the full u8 range for interop tolerance)
        let value = src[*offset] as char;
        *offset += 1;
        Ok(value)
    }
}

// ============================================================================
// [T; N] Implementation (XTypes 1.3 Section 7.4.4.2 -- fixed-size array)
// CDR2 array: N elements encoded sequentially, NO length prefix
// ============================================================================

// NOTE: encode_cdr2_le keeps the legacy sub-buffer body. See the same
// note on `impl Cdr2Encode for Vec<T>` for the rationale.
impl<T: Cdr2Encode, const N: usize> Cdr2Encode for [T; N] {
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        let mut offset = 0;
        for elem in self {
            let n = elem.encode_cdr2_le(&mut dst[offset..])?;
            offset += n;
        }
        Ok(offset)
    }
    fn max_cdr2_size(&self) -> usize {
        self.iter().map(|e| e.max_cdr2_size()).sum()
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        for elem in self {
            elem.encode_cdr2_le_at(dst, offset)?;
        }
        Ok(())
    }
}

impl<T: Cdr2Decode + Default + Copy, const N: usize> Cdr2Decode for [T; N] {
    fn decode_cdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        let mut arr = [T::default(); N];
        let mut offset = 0;
        for slot in &mut arr {
            let (val, n) = T::decode_cdr2_le(&src[offset..])?;
            *slot = val;
            offset += n;
        }
        Ok((arr, offset))
    }

    /// Spec-aligned decoder symmetric with `encode_cdr2_le_at`: no length
    /// prefix (fixed-size array), each element via `T::decode_cdr2_le_at`
    /// so the global cursor propagates uniformly.
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        let mut arr = [T::default(); N];
        for slot in &mut arr {
            *slot = T::decode_cdr2_le_at(src, offset)?;
        }
        Ok(arr)
    }
}

// ============================================================================
// Option<T> Implementation (XTypes 1.3 Section 7.4.3.5 -- optional member)
// CDR2 optional: 1-byte presence flag (0x00 absent, 0x01 present) + value
// ============================================================================

// NOTE: encode_cdr2_le keeps the legacy unaligned body — Option<u32>
// produces 5 bytes (1 flag + 4 unaligned u32) here, while
// encode_cdr2_le_at aligns to 4 after the flag (8 bytes total).
// The legacy decoder Cdr2Decode for Option<T> reads without alignment;
// changing the encoder would break roundtrip symmetry. Spec-aligned
// optional encoding for composite outer types goes through the
// _at path, not this method. Symmetric `decode_cdr2_le_at` migration is
// tracked as sous-chantier 1.6.11 in ADR-CHANTIER-1.6 §10.15.
impl<T: Cdr2Encode> Cdr2Encode for Option<T> {
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        if dst.is_empty() {
            return Err(CdrError::BufferTooSmall);
        }
        match self {
            None => {
                dst[0] = 0;
                Ok(1)
            }
            Some(val) => {
                dst[0] = 1;
                let n = val.encode_cdr2_le(&mut dst[1..])?;
                Ok(1 + n)
            }
        }
    }
    fn max_cdr2_size(&self) -> usize {
        match self {
            None => 1,
            Some(val) => 1 + val.max_cdr2_size(),
        }
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        if *offset >= dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        match self {
            None => {
                dst[*offset] = 0;
                *offset += 1;
                Ok(())
            }
            Some(val) => {
                dst[*offset] = 1;
                *offset += 1;
                val.encode_cdr2_le_at(dst, offset)
            }
        }
    }
}

impl<T: Cdr2Decode> Cdr2Decode for Option<T> {
    fn decode_cdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        if src.is_empty() {
            return Err(CdrError::UnexpectedEof);
        }
        match src[0] {
            0 => Ok((None, 1)),
            1 => {
                let (val, n) = T::decode_cdr2_le(&src[1..])?;
                Ok((Some(val), 1 + n))
            }
            v => Err(CdrError::Other(format!("invalid optional flag: {v}"))),
        }
    }

    /// Spec-aligned decoder symmetric with `encode_cdr2_le_at`: 1-byte
    /// presence flag (no alignment requirement), then the value via
    /// `T::decode_cdr2_le_at` which applies its own alignment relative
    /// to the post-flag offset.
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        if *offset >= src.len() {
            return Err(CdrError::UnexpectedEof);
        }
        let flag = src[*offset];
        *offset += 1;
        match flag {
            0 => Ok(None),
            1 => Ok(Some(T::decode_cdr2_le_at(src, offset)?)),
            v => Err(CdrError::Other(format!("invalid optional flag: {v}"))),
        }
    }
}

// ============================================================================
// BTreeMap<K, V> Implementation
// Same wire format as HashMap: u32 length + sequence of (K, V) pairs.
// Deterministic iteration order (sorted by key).
// ============================================================================

// NOTE: encode_cdr2_le keeps the legacy sub-buffer body. See the same
// note on `impl Cdr2Encode for Vec<T>` for the rationale.
impl<K: Cdr2Encode + Ord, V: Cdr2Encode> Cdr2Encode for std::collections::BTreeMap<K, V> {
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        if dst.len() < 4 {
            return Err(CdrError::BufferTooSmall);
        }
        let len = self.len() as u32;
        dst[0..4].copy_from_slice(&len.to_le_bytes());
        let mut offset = 4;
        for (key, value) in self {
            let n = key.encode_cdr2_le(&mut dst[offset..])?;
            offset += n;
            let n = value.encode_cdr2_le(&mut dst[offset..])?;
            offset += n;
        }
        Ok(offset)
    }
    fn max_cdr2_size(&self) -> usize {
        4 + self.len() * 64
    }

    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        let len = u32::try_from(self.len()).map_err(|_| CdrError::DataTooLarge)?;
        let pad = (4 - (*offset % 4)) % 4;
        if *offset + pad + 4 > dst.len() {
            return Err(CdrError::BufferTooSmall);
        }
        dst[*offset..*offset + pad].fill(0);
        *offset += pad;
        dst[*offset..*offset + 4].copy_from_slice(&len.to_le_bytes());
        *offset += 4;
        for (key, value) in self {
            key.encode_cdr2_le_at(dst, offset)?;
            value.encode_cdr2_le_at(dst, offset)?;
        }
        Ok(())
    }
}

