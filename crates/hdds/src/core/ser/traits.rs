//! CDR2 encoding/decoding traits
//!
//! These traits define the interface for types that can be serialized/deserialized
//! using CDR2 (Common Data Representation v2) format.
//!
//! These traits are designed to match the output of hdds_gen (IDL code generator),
//! allowing seamless integration between generated types and HDDS runtime.

use std::fmt;

/// Error type for CDR2 encoding/decoding operations
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CdrError {
    /// Output buffer too small for encoded data
    BufferTooSmall,

    /// Unexpected end of input buffer during decoding
    UnexpectedEof,

    /// Invalid UTF-8 encoding in string field
    InvalidEncoding,

    /// Invalid CDR2 magic bytes in header
    InvalidMagic,

    /// Data exceeds maximum encodable size (> u32::MAX bytes)
    DataTooLarge,

    /// Other error with custom message
    Other(String),
}

impl fmt::Display for CdrError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CdrError::BufferTooSmall => write!(f, "Buffer too small for CDR2 encoding"),
            CdrError::UnexpectedEof => write!(f, "Unexpected end of buffer during CDR2 decoding"),
            CdrError::InvalidEncoding => write!(f, "Invalid UTF-8 encoding in string field"),
            CdrError::InvalidMagic => write!(f, "Invalid CDR2 magic bytes"),
            CdrError::DataTooLarge => write!(f, "Data exceeds maximum encodable size (> 4GB)"),
            CdrError::Other(msg) => write!(f, "CDR2 error: {}", msg),
        }
    }
}

impl std::error::Error for CdrError {}

/// Convert CdrError to crate::Error for API compatibility
impl From<CdrError> for crate::Error {
    fn from(e: CdrError) -> Self {
        match e {
            CdrError::BufferTooSmall => crate::Error::BufferTooSmall,
            CdrError::UnexpectedEof
            | CdrError::InvalidEncoding
            | CdrError::InvalidMagic
            | CdrError::DataTooLarge
            | CdrError::Other(_) => crate::Error::SerializationError,
        }
    }
}

/// CDR2 encoding trait (Little-Endian)
///
/// Types implementing this trait can be serialized to CDR2 wire format.
/// This trait is typically implemented by hdds_gen code generator.
///
/// # Example (generated by hdds_gen ≥ 1.1.1)
///
/// Since chantier 1.6.1, only `encode_cdr2_le_at` and `max_cdr2_size` need
/// to be provided. The legacy `encode_cdr2_le(&self, dst) -> Result<usize>`
/// has a default body that delegates here, so generated code no longer
/// emits the trivial wrapper.
///
/// ```ignore
/// impl Cdr2Encode for Point {
///     fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize)
///         -> Result<(), CdrError>
///     {
///         // Write fields, advancing *offset with each one and applying
///         // alignment relative to the global *offset (not 0).
///         Ok(())
///     }
///
///     fn max_cdr2_size(&self) -> usize {
///         24
///     }
/// }
/// ```
pub trait Cdr2Encode {
    /// Encode this value into CDR2 Little-Endian format starting at offset 0.
    ///
    /// # Arguments
    /// * `dst` - Output buffer (must be large enough, check with `max_cdr2_size()`)
    ///
    /// # Returns
    /// Number of bytes written, or `CdrError::BufferTooSmall` if buffer too small
    ///
    /// # Default impl (Chantier 1.6.1f)
    /// Promoted from REQUIRED to a default that delegates to
    /// `encode_cdr2_le_at` at offset 0. This works for any type whose
    /// `_at` body is the canonical wire path. Types that need a divergent
    /// legacy wire format (cf. `Vec<T>` / `HashMap<K,V>` / `BTreeMap<K,V>`
    /// / `Option<T>` / `[T;N]` blanket impls below — kept for symmetric
    /// roundtrip with the pre-1.6.11 unaligned `Cdr2Decode` impls)
    /// continue to override.
    fn encode_cdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        // Default body since 1.6.1f. Was REQUIRED pre-1.6.1f; now any
        // impl that mirrored this body is allowed (and encouraged) to
        // drop the override entirely.
        //
        // # Warning — do NOT delegate `_at` to this
        // The reverse direction recurses forever. If a custom
        // `encode_cdr2_le_at` impl needs the trivial wire format, write
        // it inline; do not call `self.encode_cdr2_le(...)` from inside
        // `encode_cdr2_le_at`. The same warning lives on the `_at` method
        // docstring (see below).
        let mut offset = 0;
        self.encode_cdr2_le_at(dst, &mut offset)?;
        Ok(offset)
    }

    /// Get maximum size in bytes for CDR2 encoding
    ///
    /// This is a conservative estimate (may include padding/alignment overhead).
    /// Variable-size types (strings, sequences) should use worst-case estimates.
    fn max_cdr2_size(&self) -> usize;

    /// XTypes v1.3 §7.4.3.4 — Container types (sequence, map, array)
    /// recursively serialize elements using the element type's own encoding
    /// rules. For element types without native XCDR1 encoding support
    /// (not yet implemented for standard Rust container types and primitives),
    /// fall back to the XCDR2 path. This is byte-identical to XCDR2 only
    /// when elements are ≤4-byte aligned; for 8-byte-aligned elements
    /// (double, uint64, int64) the wire format follows XCDR2 alignment
    /// rules, not strict XCDR1.
    ///
    /// Overridden by types that provide an inherent `encode_xcdr1_le`
    /// method (see hdds_gen-generated code for struct/enum/union/bitset
    /// types). Rust method resolution picks the inherent first.
    fn encode_xcdr1_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        self.encode_cdr2_le(dst)
    }

    /// Default identical to `encode_cdr2_le`. Overridden by types that
    /// provide an inherent `encode_xcdr2_le` method (hdds_gen-generated
    /// code for struct/enum/union/bitset types).
    fn encode_xcdr2_le(&self, dst: &mut [u8]) -> Result<usize, CdrError> {
        self.encode_cdr2_le(dst)
    }

    /// Encode into a parent buffer at a global offset cursor.
    ///
    /// This is the spec-compliant entry point per OMG DDS-XTypes v1.3
    /// §7.4.3.4.1 Tab.15. Implementations MUST propagate `offset` to
    /// internal field encoders so alignment is computed against the
    /// real wire position rather than against `0` in a sub-buffer slice
    /// (see audit finding F01 / `cdr2_alignment` systemic for the bug
    /// that this method retires; cf. `ADR-CHANTIER-1.6-AUDIT-RESPONSE.md`
    /// §10.1 + `ADR-1.6.1-PHASE-0-CARTOGRAPHIE.md` §6.1).
    ///
    /// # Arguments
    /// * `dst` — parent buffer; the implementation writes starting at
    ///   `dst[*offset]` and advances `*offset` by the number of bytes
    ///   written (including any padding emitted for alignment).
    /// * `offset` — global cursor, mutated in-place. The caller is
    ///   responsible for any pre-call alignment; the implementation
    ///   handles its own internal alignment relative to the supplied
    ///   `*offset` value.
    ///
    /// # Returns
    /// `Ok(())` on success, `Err(CdrError::BufferTooSmall)` if `dst`
    /// is too short to hold the encoding starting at `*offset`.
    ///
    /// # Status (Chantier 1.6.1)
    /// `REQUIRED` (no default impl). The whole chantier exists to make this
    /// the canonical spec-compliant entry point and to force every
    /// `Cdr2Encode` impl to opt into the offset-propagating path. Since
    /// 1.6.1f the sibling method `encode_cdr2_le` has a default body that
    /// delegates here, so impls that want the trivial wire format do not
    /// need to write a wrapper anymore. Conversely, do NOT delegate from
    /// `_at` to `encode_cdr2_le` in a custom impl: that would call back
    /// into the default body and recurse forever.
    fn encode_cdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError>;

    /// XTypes v1.3 §7.4.3.4 — XCDR1 offset-aware sub-encoder. Default
    /// delegates to `encode_cdr2_le_at` (XCDR2 alignment rules); generated
    /// types that implement strict XCDR1 alignment override this with an
    /// inherent method via Rust method resolution. The same byte-format
    /// caveat as `encode_xcdr1_le` applies: byte-identical to XCDR2 only
    /// when elements are ≤4-byte aligned. Codegen output (hddsgen ≥1.1.0)
    /// calls `inner.encode_xcdr1_le_at(...)` on every nested field; this
    /// default makes container/primitive blanket impls work without per-
    /// type overrides.
    fn encode_xcdr1_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        self.encode_cdr2_le_at(dst, offset)
    }

    /// XTypes v1.3 §7.4.3.4 — XCDR2 offset-aware sub-encoder. Default
    /// delegates to `encode_cdr2_le_at`; generated types override with an
    /// inherent method (hddsgen ≥1.1.0). Symmetric to `encode_xcdr2_le`.
    fn encode_xcdr2_le_at(&self, dst: &mut [u8], offset: &mut usize) -> Result<(), CdrError> {
        self.encode_cdr2_le_at(dst, offset)
    }
}

/// CDR2 decoding trait (Little-Endian)
///
/// Types implementing this trait can be deserialized from CDR2 wire format.
/// This trait is typically implemented by hdds_gen code generator.
///
/// # Example (generated by hdds_gen ≥ 1.2.0)
///
/// Since chantier 1.6.2f, only `decode_cdr2_le_at` (REQUIRED, spec-aligned,
/// propagates the global offset) needs to be provided. The legacy
/// `decode_cdr2_le` has a default body that delegates to `_at` at offset
/// 0 — impls that want the trivial wire format do not need to write a
/// wrapper anymore (symmetric with `Cdr2Encode::encode_cdr2_le` since
/// chantier 1.6.1f).
///
/// ```ignore
/// impl Cdr2Decode for Point {
///     fn decode_cdr2_le_at(src: &[u8], offset: &mut usize)
///         -> Result<Self, CdrError>
///     {
///         // Read fields, advancing *offset with each one and applying
///         // alignment relative to the global *offset (not 0).
///         Ok(Point { /* ... */ })
///     }
/// }
/// ```
pub trait Cdr2Decode: Sized {
    /// Decode a value from CDR2 Little-Endian format starting at offset 0.
    ///
    /// # Arguments
    /// * `src` - Input buffer containing CDR2-encoded data
    ///
    /// # Returns
    /// Tuple of (decoded value, bytes consumed), or `CdrError` on failure.
    /// Symmetric with the legacy `Cdr2Encode::encode_cdr2_le(dst) ->
    /// Result<usize, CdrError>` (encode reports bytes written, decode
    /// reports bytes consumed).
    ///
    /// # Default impl (Chantier 1.6.2f)
    /// Promoted from REQUIRED to a default that delegates to
    /// `decode_cdr2_le_at` at offset 0. This works for any type whose
    /// `_at` body is the canonical wire path. Types that need a divergent
    /// legacy wire format (cf. `Vec<T>` / `HashMap<K,V>` / `BTreeMap<K,V>`
    /// / `Option<T>` / `[T;N]` blanket impls below — kept for symmetric
    /// roundtrip with the matching legacy `encode_cdr2_le` blanket bodies
    /// that themselves diverge from the spec-correct `_at` form)
    /// continue to override.
    ///
    /// # Warning — do NOT delegate `_at` to this
    /// The reverse direction recurses forever. If a custom
    /// `decode_cdr2_le_at` impl needs the trivial wire format, write
    /// it inline; do not call `Self::decode_cdr2_le(&src[*offset..])`
    /// from inside `decode_cdr2_le_at`. The same warning lives on the
    /// `_at` method docstring (see below).
    fn decode_cdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        // Default body since 1.6.2f. Was REQUIRED pre-1.6.2f; now any
        // impl that mirrored this body is allowed (and encouraged) to
        // drop the override entirely. Symmetric with the
        // `encode_cdr2_le` default body promoted in 1.6.1f.
        let mut offset = 0;
        let value = Self::decode_cdr2_le_at(src, &mut offset)?;
        Ok((value, offset))
    }

    /// Decode a value from a parent buffer at a global offset cursor.
    ///
    /// This is the spec-compliant entry point per OMG DDS-XTypes v1.3
    /// §7.4.3.4.1 Tab.15. Implementations MUST propagate `offset` to
    /// internal field decoders so alignment is computed against the
    /// real wire position rather than against `0` in a sub-buffer slice
    /// (symmetric with `Cdr2Encode::encode_cdr2_le_at` — both methods
    /// retire the F01 / `cdr2_alignment` systemic bug on their
    /// respective paths; cf. `ADR-CHANTIER-1.6-AUDIT-RESPONSE.md`
    /// §10.15 + `ADR-1.6.2-PHASE-0-CARTOGRAPHIE.md`).
    ///
    /// # Arguments
    /// * `src` — parent buffer; the implementation reads starting at
    ///   `src[*offset]` and advances `*offset` by the number of bytes
    ///   consumed (including any alignment padding skipped).
    /// * `offset` — global cursor, mutated in-place. The caller is
    ///   responsible for any pre-call alignment; the implementation
    ///   handles its own internal alignment relative to the supplied
    ///   `*offset` value.
    ///
    /// # Returns
    /// `Ok(Self)` on success with `*offset` advanced; `Err(CdrError::
    /// UnexpectedEof)` if `src` is too short, `Err(CdrError::Invalid*)`
    /// on malformed payloads. Symmetric with `Cdr2Encode::
    /// encode_cdr2_le_at(...) -> Result<(), CdrError>` — the only
    /// asymmetry is that decode constructs `Self` while encode mutates
    /// `dst`.
    ///
    /// # Padding bytes contract
    /// The decoder SKIPS padding bytes by advancing `*offset` without
    /// validating their value (per XTypes §7.4.3.2 Table 37: "value
    /// of padded bytes left unspecified" on encode → decode must
    /// tolerate any byte pattern in the alignment gap). Validating that
    /// padding equals zero would reject conformant frames from vendors
    /// that write arbitrary bytes there.
    ///
    /// # Warning — do NOT delegate this to `decode_cdr2_le`
    /// Writing `Self::decode_cdr2_le(&src[*offset..])` inside an impl
    /// of `decode_cdr2_le_at` defeats the alignment correctness this
    /// method exists to achieve: the callee resets to offset 0 and
    /// aligns relative to the sub-buffer slice, not the global offset.
    /// Implement the decode logic natively, propagating `offset` to
    /// every inner field decoder. The same warning lives on the
    /// `Cdr2Encode::encode_cdr2_le_at` docstring.
    ///
    /// # Status (Chantier 1.6.2)
    /// `REQUIRED` (no default impl on purpose, mirroring
    /// `encode_cdr2_le_at`). The migration explicitly opts out of
    /// opt-in correctness so the compiler enforces exhaustive coverage
    /// of all `Cdr2Decode` impls — each unmigrated impl surfaces as an
    /// E0046 build error rather than silently falling back to a
    /// (broken) default body. Since 1.6.2f the sibling method
    /// `decode_cdr2_le` has a default body that delegates here, so
    /// impls that want the trivial wire format do not need to write a
    /// wrapper anymore. Conversely, do NOT delegate from `_at` to
    /// `decode_cdr2_le` in a custom impl: that would call back into the
    /// default body and recurse forever.
    fn decode_cdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError>;

    /// XTypes v1.3 §7.4.3.4 — Symmetric fallback for XCDR1 decoding.
    /// See `Cdr2Encode::encode_xcdr1_le` for rationale. Overridden by
    /// types that provide an inherent `decode_xcdr1_le` method
    /// (hdds_gen-generated code for struct/enum/union/bitset types).
    fn decode_xcdr1_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        Self::decode_cdr2_le(src)
    }

    /// Default identical to `decode_cdr2_le`. Overridden by types that
    /// provide an inherent `decode_xcdr2_le` method (hdds_gen-generated
    /// code for struct/enum/union/bitset types).
    fn decode_xcdr2_le(src: &[u8]) -> Result<(Self, usize), CdrError> {
        Self::decode_cdr2_le(src)
    }

    /// XTypes v1.3 §7.4.3.4 — XCDR1 offset-aware sub-decoder. Default
    /// delegates to `decode_cdr2_le_at` (XCDR2 alignment rules, cap-4);
    /// generated types that implement strict XCDR1 alignment (natural
    /// align without cap) override this with an inherent method via
    /// Rust method resolution. The same byte-format caveat as
    /// `decode_xcdr1_le` applies: byte-identical to XCDR2 only when
    /// elements are ≤4-byte aligned. Codegen output (hddsgen ≥1.2.0)
    /// calls `inner.decode_xcdr1_le_at(...)` on every nested field;
    /// this default makes container/primitive blanket impls work
    /// without per-type overrides. Symmetric with
    /// `Cdr2Encode::encode_xcdr1_le_at`.
    fn decode_xcdr1_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        Self::decode_cdr2_le_at(src, offset)
    }

    /// XTypes v1.3 §7.4.3.4 — XCDR2 offset-aware sub-decoder. Default
    /// delegates to `decode_cdr2_le_at`; generated types override with
    /// an inherent method (hddsgen ≥1.2.0). Symmetric with
    /// `Cdr2Encode::encode_xcdr2_le_at`.
    fn decode_xcdr2_le_at(src: &[u8], offset: &mut usize) -> Result<Self, CdrError> {
        Self::decode_cdr2_le_at(src, offset)
    }
}

